const indexFile = path.join(ROOT, 'mobile/wordbank-json/index.json')
const index = JSON.parse(fs.readFileSync(indexFile, 'utf8'))
  .filter(item => item.id !== 'movie-tv-vocab' && !Object.values(BANK_META).some(bank => bank.id === item.id))
const allSeen = new Set()

for (const collection of COLLECTIONS) {
  const meta = BANK_META[collection.source]
  const sourceWords = [
    ...collection.words,
    ...(EXTRA_WORDS[collection.source] || []),
    ...(ADVANCED_WORDS[collection.source] || []),
  ]
  if (sourceWords.length !== 50) throw new Error(`${collection.source} 词数为 ${sourceWords.length}，应为 50`)

  const words = sourceWords.map(([word, meaning], index) => {
    const key = word.toLowerCase()
    if (allSeen.has(key)) throw new Error(`跨词库重复词条：${word}`)
    allSeen.add(key)
    const level = index < 17 ? '入门' : index < 36 ? '进阶' : '高阶'
    return {
      word,
      explains: `${meaning}（${level}高频）`,
      freq: index + 1,
    }
  })

  const publicFile = path.join(ROOT, 'public/wordbanks', `${meta.id}.json`)
  const mobileFile = path.join(ROOT, 'mobile/wordbank-json', `${meta.id}.json`)
  fs.writeFileSync(publicFile, JSON.stringify(words, null, 2))
  fs.writeFileSync(mobileFile, JSON.stringify(words))
  const sizeKB = Math.round(fs.statSync(publicFile).size / 1024)
  index.push({ id: meta.id, name: meta.name, wordCount: words.length, sizeKB })
  console.log(`✓ ${meta.id}: ${words.length} 词，${sizeKB}KB`)
}

